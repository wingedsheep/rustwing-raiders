/** Rows of bits per glyph, parsed once. */
const GLYPHS = new Map<string, number[]>();
for (const [ch, rows] of Object.entries(G)) GLYPHS.set(ch, rows.split(' ').map((r) => parseInt(r, 2)));

export const CHAR_W = 6;
export const LINE_H = 9;

export function textWidth(s: string, scale = 1) {
  return s.length * CHAR_W * scale - scale;
}

/**
 * Draws text at (x, y) (top-left), `scale` times the size. With `shadow`, a dark drop shadow one
 * texel down-right, which keeps it readable over anything.
 */
export function drawText(
  ctx: CanvasRenderingContext2D,
  s: string,
  x: number,
  y: number,
  color = '#f4ecd8',
  opts: { scale?: number; shadow?: string | false; align?: 'left' | 'center' | 'right' } = {},
) {
  const scale = opts.scale ?? 1;
  const text = s.toUpperCase();
  const w = textWidth(text, scale);
  let x0 = Math.round(opts.align === 'center' ? x - w / 2 : opts.align === 'right' ? x - w : x);
  const y0 = Math.round(y);
  const shadow = opts.shadow === undefined ? '#120c18' : opts.shadow;
  if (shadow) blit(ctx, text, x0 + scale, y0 + scale, shadow, scale);
  blit(ctx, text, x0, y0, color, scale);
  return w;
}

function blit(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, scale: number) {
  ctx.fillStyle = color;
  for (const ch of text) {
    const g = GLYPHS.get(ch) ?? GLYPHS.get('?')!;
    for (let r = 0; r < 7; r++) {
      const bits = g[r];
      if (!bits) continue;
      for (let c = 0; c < 5; c++) if (bits & (1 << (4 - c))) ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
    }
    x += CHAR_W * scale;
  }
}

/** Splits text into lines that fit `width` texels. */
export function wrap(s: string, width: number, scale = 1): string[] {
  const words = s.split(/\s+/);
  const lines: string[] = [];
  let line = '';
  for (const w of words) {
    const next = line ? `${line} ${w}` : w;
    if (textWidth(next, scale) > width && line) {
      lines.push(line);
      line = w;
    } else line = next;
  }
  if (line) lines.push(line);
  return lines;
}
