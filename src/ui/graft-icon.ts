/** A graft's picture, `scale` texels a dot, top-left at (x, y). `dim`: greyed. */
export function graftIcon(ctx: CanvasRenderingContext2D, g: GraftId, x: number, y: number, scale = 1, dim = false) {
  const f = GRAFTS[g].faction;
  const col = { '#': dim ? '#5a5068' : FACTION_COLOR[f], '+': dim ? '#8a8098' : INK, o: dim ? '#2a2234' : FACTION_DARK[f] } as Record<string, string>;
  ICONS[g].forEach((row, r) => {
    for (let c = 0; c < row.length; c++) {
      const fill = col[row[c]];
      if (!fill) continue;
      ctx.fillStyle = fill;
      ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
    }
  });
}

export const ICON_SIZE = 12;
