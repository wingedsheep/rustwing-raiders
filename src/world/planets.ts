/**
 * The planets of the run. Every planet is a handful of biomes that a level flies through in turn,
 * so a world is never one thing: Oru-Tal is fern jungle with grazing giants, then black basalt
 * steps over lava, then cliffs of crystal, then a jade-green sea.
 *
 * Props and creatures are named by kind (see world/props-*.ts and world/creatures.ts); terrain
 * by shape (see world/terrain.ts). Colours are hex.
 */

export type TerrainShape =
  | 'rolling' // soft hills
  | 'terraces' // stepped plateaus
  | 'ridges' // sharp crests and cliffs
  | 'islands' // mostly sea, with islands
  | 'dunes' // long wind-combed waves of sand
  | 'flats' // near flat, cracked
  | 'craters' // pocked with bowls
  | 'marsh' // low and wet, pools everywhere
  | 'canyon'; // a winding gorge with walls taller than you fly

export type Particles = 'ash' | 'embers' | 'spores' | 'snow' | 'rain' | 'sand' | 'pollen' | 'motes' | 'steam' | 'none';

export interface Biome {
  id: string;
  name: string;
  /** One line, shown as the biome slides into view. */
  line: string;
  shape: TerrainShape;
  /** Height of the land, roughly (units; you fly at 10). */
  relief: number;
  /** Sea / lava / chemical level, or null for dry land. */
  water: number | null;
  waterColor: number;
  /** The liquid glows (lava, chemicals, bioluminescence). */
  waterGlow?: number;
  /** Ground from low to high: shore, low, mid, high. */
  ground: [number, number, number, number];
  /** Steep faces. */
  cliff: number;
  /** Props: [kind, weight]. `density` is props per 100 square units. */
  props: [string, number][];
  density: number;
  creatures: [string, number][];
  particles: Particles;
  /** The light: sun colour, sky (ambient from above), bounce (ambient from below). */
  sun: number;
  sky: number;
  bounce: number;
  /** Low clouds drifting under you (colour), or null. */
  clouds: number | null;
  /** Grade: shadows lean towards `shade`, lit parts towards `light`. */
  shade: number;
  light: number;
  /** Lightning, falling rocks, geysers... things that happen here. */
  hazards: string[];
}

export type Archetype =
  | 'dart' // quick swooping fighters in formation
  | 'gunship' // hovers in, fires spreads, leaves
  | 'turret' // on the ground, tracks you
  | 'bomber' // slow, lays mines and flak
  | 'lancer' // stops, telegraphs, fires a beam
  | 'swarm' // a flock of small beasts
  | 'brute' // big and tough, spirals of shots
  | 'serpent' // bursts out of sea or sand, segmented
  | 'carrier'; // drops smaller ships

export interface EnemySkin {
  archetype: Archetype;
  name: string;
  /** Machine or beast: sets the model family. */
  kind: 'mech' | 'beast';
  colors: [number, number, number];
}

export interface Planet {
  id: string;
  name: string;
  epithet: string;
  blurb: string;
  /** Colours of the planet seen from orbit, banded like its biomes. */
  orbit: number[];
  ring?: number;
  /** Who you fight here. */
  faction: string;
  biomes: Biome[];
  enemies: EnemySkin[];
  boss: { name: string; title: string; kind: 'mech' | 'beast'; colors: [number, number, number] };
}

